/**
 * 在线办公功能清单(单机版占位用)。
 *
 * 「察元 AI 桌面单机版」是免费的本地离线版本,不包含需要服务端协同的「在线办公」
 * 能力。下面这组功能在完整在线版(chayuan-client 在线部署)里存在,这里只保留
 * **菜单占位 + 功能介绍**,点击后进入 OnlineFeaturePage 做流式介绍并引导联系商务。
 *
 * 每条 ``intro`` 文案基于在线版实际页面代码归纳(察元办公 / 智能空间 / 应用市场 /
 * 我的待办 / 训练数据中心),不是营销虚词,描述的是该功能真实能做什么。
 *
 * paragraphs:占位页流式打字机逐段输出的内容。打字机对**静态文案**做分块渲染,
 * 不调用任何 LLM —— 单机版要求完全离线可用,且文案固定。
 */

export interface OnlineFeature {
  /** 路由 key,占位页路由形如 /online/<key> */
  key: string;
  /** 侧边栏 / Tab 标题 */
  title: string;
  /** lucide 图标名(与 deriveIcon 对齐) */
  icon: string;
  /** 一句话定位,显示在占位页标题下方 */
  tagline: string;
  /** 流式输出的功能介绍段落(逐段打字机渲染) */
  paragraphs: ReadonlyArray<string>;
  /**
   * 深度介绍内容(可选)。只有「我的待办」配了 rich,占位页检测到后渲染富版:
   * 顶部仍打字机流式输出 paragraphs,下面分多个功能板块,每块带 SVG 示意截图。
   * 其它在线功能不配 rich,继续走简单占位页。
   */
  rich?: RichFeature;
}

/** 深度介绍页的一个功能板块。 */
export interface RichSection {
  /** 板块小标题 */
  heading: string;
  /** lucide 图标名 */
  icon: string;
  /** 板块说明文字(1~N 段) */
  body: ReadonlyArray<string>;
  /**
   * 配图 mockup 的 id —— 与 TasklistMockups.tsx 导出的示意图组件一一对应。
   * undefined 表示该板块不配图,只出文字。
   */
  mockup?: 'views' | 'conversational-form' | 'flow-handoff';
  /** 该板块的要点清单(可选,以 • 列表呈现) */
  highlights?: ReadonlyArray<string>;
}

/** 深度介绍内容(目前仅「我的待办」使用)。 */
export interface RichFeature {
  /** 深度介绍页的功能板块,按顺序渲染 */
  sections: ReadonlyArray<RichSection>;
}

